out = ["/* type-icons.css — generated pixel icons for the 18 types.",
"   9x9 bitmaps drawn as SVG masks, painted in the badge's text colour, so",
"   every phone and browser shows the same icon (no emoji fallbacks).",
"   Generated by scripts/gen_type_icons.py; edit the bitmaps there and rerun",
"   it from the repo root rather than editing this file. */",
".px-ti {",
"  display: inline-block;",
"  flex: none;",
"  width: 1em;",
"  height: 1em;",
"  background-color: currentColor;",
"  -webkit-mask: var(--ti) center / contain no-repeat;",
"          mask: var(--ti) center / contain no-repeat;",
"  image-rendering: pixelated;",
"  vertical-align: -0.12em;",
"}"]
for k,v in I.items():
    rows=[r for r in v.strip("\n").split("\n")]
    assert len(rows)==9 and all(len(r)==9 for r in rows),k
    rects="".join(f"<rect x='{x}' y='{y}' width='1' height='1'/>" for y,r in enumerate(rows) for x,ch in enumerate(r) if ch=="#")
    svg=f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 9 9' shape-rendering='crispEdges'>{rects}</svg>"
    uri="data:image/svg+xml,"+urllib.parse.quote(svg, safe="/:=' ")
    out.append(f'.px-ti-{k} {{ --ti: url("{uri}"); }}')
open("frontend/type-icons.css","w").write("\n".join(out)+"\n")
print(f"wrote {len(I)} icons to frontend/type-icons.css")
